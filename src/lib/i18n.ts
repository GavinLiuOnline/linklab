type Key = keyof typeof zh;
export type I18nKey = Key;
const DICT: Record<Lang, Partial<Record<Key, string>>> = { zh, en };

/** 组件内：const t = useT(); t("send.send") */
export function useT() {
  const { settings } = useStore(uiStore);
  const lang = settings.lang ?? "zh";
  return (key: Key): string => DICT[lang][key] ?? zh[key];
}
